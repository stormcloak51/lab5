n = int(input("Введите число: "))
original = n
facs = []

divisor = 2
while divisor * divisor <= n:
    # пока число делится на простой множитель
    while n % divisor == 0:
        facs.append(divisor)
        n //= divisor
    # скалдываем на единицу, т.к. следующие числа будут делиться на меньшие простые числа
    # например, если у нас будет 4, условия деления на это число соблюдаться не будет,
    # потому что мы уже перечислили все простые делители (это 2, 4 = 2 * 2)
    divisor += 1

if n > 1:
    facs.append(n)

# map(str, facs) - преобразует все числовые элементы массива на строковые
print(f"{original} = {' × '.join(map(str, facs))}")
